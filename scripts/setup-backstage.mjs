// Prepares a checked out Backstage app for the tests:
//
//   node scripts/setup-backstage.mjs <backstage-app-dir>
//
// New frontend system (1.49+): writes app-config/app-config.nfs.yaml as
// app-config.local.yaml. Config lists aren't merged across config files, so
// its app.extensions are appended to the app's own app.extensions list.
//
// Old frontend system (up to 1.48): copies app-config/app-config.ofs.yaml as
// app-config.local.yaml and adds the languages to createApp() in App.tsx,
// since the old frontend system can't enable translations via config.
//
// Must run after the app's dependencies are installed; the YAML parser is
// loaded from the app's node_modules.

import { copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const appDir = resolve(process.argv[2] ?? '');
if (!process.argv[2]) {
  console.error('Usage: node scripts/setup-backstage.mjs <backstage-app-dir>');
  process.exit(1);
}

const configDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'app-config');
const YAML = createRequire(join(appDir, 'package.json'))('yaml');
const readYaml = file => YAML.parse(readFileSync(file, 'utf8')) ?? {};

const extensionId = entry =>
  typeof entry === 'string' ? entry : Object.keys(entry ?? {})[0];

const nfsConfig = readYaml(join(configDir, 'app-config.nfs.yaml'));
const languageExtension = nfsConfig.app.extensions.find(
  entry => extensionId(entry) === 'api:app/app-language',
);
const { availableLanguages } = languageExtension['api:app/app-language'].config;

const appPackage = JSON.parse(
  readFileSync(join(appDir, 'packages/app/package.json'), 'utf8'),
);
const isNewFrontendSystem = Boolean(
  appPackage.dependencies?.['@backstage/frontend-defaults'],
);
const localConfigFile = join(appDir, 'app-config.local.yaml');

if (isNewFrontendSystem) {
  const appConfig = readYaml(join(appDir, 'app-config.yaml'));
  const ownIds = new Set(nfsConfig.app.extensions.map(extensionId));
  const appExtensions = (appConfig.app?.extensions ?? []).filter(
    entry => !ownIds.has(extensionId(entry)),
  );
  const localConfig = {
    ...nfsConfig,
    app: {
      ...nfsConfig.app,
      extensions: [...appExtensions, ...nfsConfig.app.extensions],
    },
  };
  writeFileSync(
    localConfigFile,
    `# Generated by scripts/setup-backstage.mjs from app-config.nfs.yaml and\n# the app.extensions of app-config.yaml.\n${YAML.stringify(localConfig)}`,
  );
  console.log(
    `New frontend system: wrote ${localConfigFile} with ${localConfig.app.extensions.length} extensions.`,
  );
} else {
  copyFileSync(join(configDir, 'app-config.ofs.yaml'), localConfigFile);

  const appFile = join(appDir, 'packages/app/src/App.tsx');
  const source = readFileSync(appFile, 'utf8');
  const marker = 'const app = createApp({';
  if (source.includes('__experimentalTranslations')) {
    throw new Error(`${appFile} already configures __experimentalTranslations`);
  }
  if (!source.includes(marker)) {
    throw new Error(`Could not find "${marker}" in ${appFile}`);
  }
  const translations = `\n  __experimentalTranslations: {\n    availableLanguages: [${availableLanguages.map(l => `'${l}'`).join(', ')}],\n  },`;
  writeFileSync(appFile, source.replace(marker, `${marker}${translations}`));
  console.log(
    `Old frontend system: copied ${localConfigFile} and added languages ${availableLanguages.join(', ')} to ${appFile}.`,
  );
}
